export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export interface I18n {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translate;
  formatNumber: (value: number) => string;
  formatDate: (iso: string) => string;
  formatDateTime: (iso: string) => string;
  /** Message for an IPC or dialog error, translated when the backend message is known. */
  errorText: (error: unknown) => string;
}

function interpolate(template: string, values?: Record<string, string | number>) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => name in values ? String(values[name]) : match);
}

function createI18n(language: Language, setLanguage: (language: Language) => void): I18n {
  const messages = MESSAGES[language];
  const locale = LOCALES[language];
  const numberFormat = new Intl.NumberFormat(locale, { maximumFractionDigits: 2 });
  const t: Translate = (key, values) => interpolate(messages[key] ?? en[key], values);
  const parse = (iso: string) => { const date = new Date(iso); return Number.isNaN(date.getTime()) ? null : date; };
  return {
    language,
    setLanguage,
    t,
    formatNumber: value => numberFormat.format(value),
    formatDate: iso => parse(iso)?.toLocaleDateString(locale) ?? iso,
    formatDateTime: iso => parse(iso)?.toLocaleString(locale, { dateStyle: "short", timeStyle: "short" }) ?? iso,
    errorText: error => {
      const raw = error instanceof Error ? error.message : String(error);
      if (language === "en") return raw;
      const match = ERROR_PATTERNS.find(([pattern]) => pattern.test(raw));
      return match ? t(match[1]) : raw;
    },
  };
}

export function detectLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "gl" || stored === "es" || stored === "en") return stored;
  } catch { /* Fall back to the system language. */ }
  const preferred = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of preferred) {
    const base = tag?.toLowerCase().split("-")[0];
    if (base === "gl" || base === "es" || base === "en") return base;
  }
  return "en";
}

const I18nContext = createContext<I18n>(createI18n("en", () => {}));

export function I18nProvider({ children, initialLanguage }: { children: ReactNode; initialLanguage?: Language }) {
  const [language, setLanguageState] = useState<Language>(() => initialLanguage ?? detectLanguage());
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const value = useMemo(() => createI18n(language, next => {
    setLanguageState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* The choice applies to this session only. */ }
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  return useContext(I18nContext);
}
